const DEFAULT_REPORT_DATE = '30-09-2026';

function mapPrismaStatusToFrontend(status: EmailCampaignStatus): string {
  switch (status) {
    case EmailCampaignStatus.DRAFT:
      return 'Draft';
    case EmailCampaignStatus.READY:
      return 'Ready';
    case EmailCampaignStatus.APPROVED:
      return 'Approved';
    case EmailCampaignStatus.QUEUED:
      return 'Queued';
    case EmailCampaignStatus.SENT:
      return 'Sent';
    case EmailCampaignStatus.DELIVERED:
      return 'Delivered';
    case EmailCampaignStatus.FAILED:
      return 'Failed';
    case EmailCampaignStatus.BOUNCED:
      return 'Bounced';
    default:
      return 'Draft';
  }
}

function formatShortTimestamp(dt: Date | null | undefined): string | undefined {
  if (!dt) return undefined;
  const dd = String(dt.getDate()).padStart(2, '0');
  const mm = String(dt.getMonth() + 1).padStart(2, '0');
  const yyyy = dt.getFullYear();
  const hh = String(dt.getHours()).padStart(2, '0');
  const min = String(dt.getMinutes()).padStart(2, '0');
  return `${dd}-${mm}-${yyyy} ${hh}:${min}`;
}

