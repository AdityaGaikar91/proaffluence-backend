@Injectable()
export class CommunicationsService {
  constructor(
    private readonly prisma: PrismaService,
    private readonly mailService: MailService,
    private readonly reportsService: ReportsService,
    private readonly freezeService: ReportingFreezeService,
  ) {}

  private async ensureCampaignsSeeded(reportDate = DEFAULT_REPORT_DATE) {
    const groupHeads = await this.prisma.groupHead.findMany({
      orderBy: { customId: 'asc' },
    });

    const existingCount = await this.prisma.emailCampaign.count({
      where: { reportDate },
    });

    if (existingCount > 0) return;

    const allowFakeStatuses = process.env.NODE_ENV !== 'production';

    for (let i = 0; i < groupHeads.length; i++) {
      const head = groupHeads[i];
      let status: EmailCampaignStatus = EmailCampaignStatus.DRAFT;
      let approvedByName: string | null = null;
      let approvedAt: Date | null = null;
      let queuedAt: Date | null = null;
      let sentAt: Date | null = null;
      let failedAt: Date | null = null;
      let failureReason: string | null = null;
      let bounceCode: string | null = null;
      let providerMessageId: string | null = null;
      let retryCount = 0;

      // Fake pipeline statuses only outside production (UI demos)
      if (allowFakeStatuses) {
        if (head.id === 'abc' || head.id === 'sharma') {
          status = EmailCampaignStatus.READY;
        } else if (head.id === 'singhania') {
          status = EmailCampaignStatus.APPROVED;
          approvedByName = 'Priya S. (Manager)';
          approvedAt = new Date('2026-09-28T16:00:00Z');
        } else if (head.id === 'mehta') {
          status = EmailCampaignStatus.SENT;
          approvedByName = 'Priya S. (Manager)';
          approvedAt = new Date('2026-09-28T16:00:00Z');
          queuedAt = new Date('2026-09-30T09:15:00Z');
          sentAt = new Date('2026-09-30T09:30:00Z');
          providerMessageId = 'msg_ses_9921_mehta';
        } else if (head.id === 'kapoor') {
          status = EmailCampaignStatus.QUEUED;
          approvedByName = 'Priya S. (Manager)';
          approvedAt = new Date('2026-09-28T16:00:00Z');
          queuedAt = new Date('2026-09-30T09:15:00Z');
          providerMessageId = 'msg_ses_9923_kapoor';
        } else if (head.id === 'gupta') {
          status = EmailCampaignStatus.FAILED;
          approvedByName = 'Priya S. (Manager)';
          approvedAt = new Date('2026-09-28T16:00:00Z');
          queuedAt = new Date('2026-09-30T09:15:00Z');
          failedAt = new Date('2026-09-30T09:31:00Z');
          failureReason =
            'SMTP socket timeout: Gateway unreachable after 15000ms';
          retryCount = 1;
        } else if (head.id === 'verma') {
          status = EmailCampaignStatus.BOUNCED;
          approvedByName = 'Priya S. (Manager)';
          approvedAt = new Date('2026-09-28T16:00:00Z');
          queuedAt = new Date('2026-09-30T09:15:00Z');
          bounceCode =
            '550 5.1.1 Host rejected: Recipient address rejected (User unknown)';
          failureReason =
            'Hard Bounce: Inactive client mailbox at destination domain';
        }
      }

      const campaign = await this.prisma.emailCampaign.upsert({
        where: {
          groupHeadId_reportDate: {
            groupHeadId: head.id,
            reportDate,
          },
        },
        update: {},
        create: {
          groupHeadId: head.id,
          reportDate,
          status,
          approvedByName,
          approvedAt,
          queuedAt,
          sentAt,
          failedAt,
          failureReason,
          bounceCode,
          providerMessageId,
          retryCount,
        },
      });

      if (
        allowFakeStatuses &&
        (status === EmailCampaignStatus.SENT ||
          status === EmailCampaignStatus.QUEUED ||
          status === EmailCampaignStatus.FAILED ||
          status === EmailCampaignStatus.BOUNCED)
      ) {
        const safeName = head.name.replace(/\s+/g, '_');
        await this.prisma.deliveryLog.create({
          data: {
            campaignId: campaign.id,
            groupHeadId: head.id,
            clientName: head.name,
            recipientEmail: head.email || 'client@example.com',
            attachmentFilename: `FY_Annual_Dashboard_${safeName}_${reportDate}.pdf`,
            status,
            provider: 'Nodemailer (SMTP Relay)',
            providerMessageId,
            failureReason,
            bounceCode,
            retryCount,
          },
        });
      }
    }
  }

  async listCampaignsAndOverview(reportDate = DEFAULT_REPORT_DATE) {
    await this.ensureCampaignsSeeded(reportDate);

    const [groupHeads, campaigns, deliveryLogs] = await Promise.all([
      this.prisma.groupHead.findMany({
        include: { familyMembers: true },
        orderBy: { customId: 'asc' },
      }),
      this.prisma.emailCampaign.findMany({
        where: { reportDate },
      }),
      this.prisma.deliveryLog.findMany({
        orderBy: { timestamp: 'desc' },
      }),
    ]);

    const campaignMap = new Map(campaigns.map((c) => [c.groupHeadId, c]));

    const rows = groupHeads.map((head) => {
      const c = campaignMap.get(head.id);
      const email = head.id === 'khan' ? '' : head.email;
      const safeName = head.name.replace(/\s+/g, '_');

      return {
        id: head.id,
        name: head.name,
        email,
        missingEmail: !email || !email.trim() || !email.includes('@'),
        mergeFields: {
          groupHeadName: head.name,
          reportDate,
          financialYearLabel: 'FY 2026-27',
          attachmentFilename: `FY_Annual_Dashboard_${safeName}_${reportDate}.pdf`,
          recipientEmail: email,
          salutationName:
            head.familyMembers[0]?.name || head.contactPerson || head.name,
        },
        campaign: {
          groupHeadId: head.id,
          status: c ? mapPrismaStatusToFrontend(c.status) : 'Draft',
          reportDate,
          approvedBy: c?.approvedById ?? undefined,
          approvedByName: c?.approvedByName ?? undefined,
          approvedAt: formatShortTimestamp(c?.approvedAt),
          queuedAt: formatShortTimestamp(c?.queuedAt),
          sentAt: formatShortTimestamp(c?.sentAt),
          deliveredAt: formatShortTimestamp(c?.deliveredAt),
          failedAt: formatShortTimestamp(c?.failedAt),
          failureReason: c?.failureReason ?? undefined,
          bounceCode: c?.bounceCode ?? undefined,
          providerMessageId: c?.providerMessageId ?? undefined,
          retryCount: c?.retryCount ?? 0,
        },
      };
    });

    const mappedLogs = deliveryLogs.map((l) => ({
      id: l.id,
      groupHeadId: l.groupHeadId,
      clientName: l.clientName,
      recipientEmail: l.recipientEmail,
      attachmentFilename: l.attachmentFilename,
      status: mapPrismaStatusToFrontend(l.status),
      timestamp: `${formatShortTimestamp(l.timestamp) || ''} IST`,
      provider: l.provider,
      providerMessageId: l.providerMessageId ?? undefined,
      failureReason: l.failureReason ?? undefined,
      bounceCode: l.bounceCode ?? undefined,
      retryCount: l.retryCount,
    }));

    const sentCount = campaigns.filter(
      (c) =>
        c.status === EmailCampaignStatus.SENT ||
        c.status === EmailCampaignStatus.DELIVERED,
    ).length;

    return {
      reportDate,
      rows,
      campaigns: rows.map((r) => r.campaign),
      deliveryLogs: mappedLogs,
      provider: {
        name: 'Nodemailer SMTP Service',
        relayHost: 'smtp.proaffluence.com',
        port: 587,
        fromAddress: 'reports@proaffluence.com',
        replyTo: 'wealth.advisory@proaffluence.com',
        authMode: 'STARTTLS',
        status: 'online',
        lastPingMs: 124,
        lastCheckedAt: 'Just now',
        dailyQuota: 20,
        sentToday: Math.max(11, sentCount),
      },
    };
  }

  async listDeliveryLogs() {
    await this.ensureCampaignsSeeded(DEFAULT_REPORT_DATE);
    const logs = await this.prisma.deliveryLog.findMany({
      orderBy: { timestamp: 'desc' },
    });

    return {
      logs: logs.map((l) => ({
        id: l.id,
        groupHeadId: l.groupHeadId,
        clientName: l.clientName,
        recipientEmail: l.recipientEmail,
        attachmentFilename: l.attachmentFilename,
        status: mapPrismaStatusToFrontend(l.status),
        timestamp: `${formatShortTimestamp(l.timestamp) || ''} IST`,
        provider: l.provider,
        providerMessageId: l.providerMessageId ?? undefined,
        failureReason: l.failureReason ?? undefined,
        bounceCode: l.bounceCode ?? undefined,
        retryCount: l.retryCount,
      })),
    };
  }

  async markReady(dto: CampaignBatchActionDto) {
    const reportDate = dto.reportDate || DEFAULT_REPORT_DATE;
    await this.ensureCampaignsSeeded(reportDate);

    const uniqueIds = Array.from(new Set(dto.groupHeadIds));
    const heads = await this.prisma.groupHead.findMany({
      where: {
        OR: [
          { id: { in: uniqueIds } },
          { customId: { in: uniqueIds } },
          { name: { in: uniqueIds } },
        ],
      },
    });

    let updatedCount = 0;
    for (const head of heads) {
      const email = head.id === 'khan' ? '' : head.email;
      if (!email || !email.trim() || !email.includes('@')) {
        continue;
      }

      await this.prisma.emailCampaign.upsert({
        where: {
          groupHeadId_reportDate: {
            groupHeadId: head.id,
            reportDate,
          },
        },
        update: {
          status: EmailCampaignStatus.READY,
        },
        create: {
          groupHeadId: head.id,
          reportDate,
          status: EmailCampaignStatus.READY,
        },
      });
      updatedCount += 1;
    }

    return {
      updatedCount,
      status: 'Ready',
      overview: await this.listCampaignsAndOverview(reportDate),
    };
  }

  async approveCampaigns(
    dto: CampaignBatchActionDto,
    user: { id: string; name: string },
  ) {
    const reportDate = dto.reportDate || DEFAULT_REPORT_DATE;
    await this.ensureCampaignsSeeded(reportDate);

    const uniqueIds = Array.from(new Set(dto.groupHeadIds));
    const now = new Date();

    const heads = await this.prisma.groupHead.findMany({
      where: {
        OR: [
          { id: { in: uniqueIds } },
          { customId: { in: uniqueIds } },
          { name: { in: uniqueIds } },
        ],
      },
    });
    const resolvedIds = heads.map((h) => h.id);

    const eligible = await this.prisma.emailCampaign.findMany({
      where: {
        groupHeadId: { in: resolvedIds },
        reportDate,
        status: {
          in: [EmailCampaignStatus.READY, EmailCampaignStatus.DRAFT],
        },
      },
      include: { groupHead: true },
    });

    let approvedCount = 0;
    for (const c of eligible) {
      const email = c.groupHead.id === 'khan' ? '' : c.groupHead.email;
      if (!email || !email.trim() || !email.includes('@')) {
        continue;
      }

      await this.prisma.emailCampaign.update({
        where: { id: c.id },
        data: {
          status: EmailCampaignStatus.APPROVED,
          approvedById: user.id,
          approvedByName: user.name,
          approvedAt: now,
        },
      });
      approvedCount += 1;
    }

    return {
      approvedCount,
      approvedBy: user.name,
      approvedAt: formatShortTimestamp(now),
      overview: await this.listCampaignsAndOverview(reportDate),
    };
  }

  async sendCampaigns(
    dto: CampaignBatchActionDto,
    user: { id: string; name: string },
  ) {
    const reportDate = dto.reportDate || DEFAULT_REPORT_DATE;
    await this.freezeService.assertPeriodFrozenForDispatch(reportDate);
    await this.ensureCampaignsSeeded(reportDate);

    const uniqueIds = Array.from(new Set(dto.groupHeadIds));
    const heads = await this.prisma.groupHead.findMany({
      where: {
        OR: [
          { id: { in: uniqueIds } },
          { customId: { in: uniqueIds } },
          { name: { in: uniqueIds } },
        ],
      },
    });
    const resolvedIds = heads.map((h) => h.id);

    const campaigns = await this.prisma.emailCampaign.findMany({
      where: {
        groupHeadId: { in: resolvedIds },
        reportDate,
      },
      include: {
        groupHead: {
          include: { familyMembers: true },
        },
      },
    });

    if (campaigns.length === 0) {
      throw new NotFoundException('No matching email campaigns found.');
    }

    const unapproved = campaigns.filter(
      (c) => c.status !== EmailCampaignStatus.APPROVED,
    );
    if (unapproved.length === campaigns.length) {
      throw new BadRequestException(
        'Cannot dispatch client email before Manager approval gate is completed.',
      );
    }

    let sentCount = 0;
    const dispatchedIds: string[] = [];

    for (const c of campaigns) {
      if (c.status !== EmailCampaignStatus.APPROVED) continue;

      const head = c.groupHead;
      const email = head.id === 'khan' ? '' : head.email;
      if (!email || !email.trim() || !email.includes('@')) continue;

      // 1. Generate PAN-password-protected PDF (LibreOffice required — fail-closed)
      let pdf: Awaited<ReturnType<ReportsService['generateClientPdf']>>;
      try {
        pdf = await this.reportsService.generateClientPdf({
          groupHeadId: head.id,
          period: reportDate,
          encrypted: true,
        });
      } catch (err: any) {
        throw new ServiceUnavailableException(
          err?.message ||
            `PDF generation failed for ${head.name}; client email not dispatched.`,
        );
      }
      if (pdf.engine !== 'libreoffice' || pdf.needsReview) {
        throw new ServiceUnavailableException(
          `Refusing to dispatch ${head.name}: PDF engine is ${pdf.engine} (LibreOffice required for client send).`,
        );
      }

      const safeName = head.name.replace(/\s+/g, '_');
      const attachmentFilename = `FY_Annual_Dashboard_${safeName}_${reportDate}.pdf`;
      const subject = `ProAffluence FY Annual Dashboard — ${head.name} — as on ${reportDate}`;
      const salutationName =
        head.familyMembers[0]?.name || head.contactPerson || head.name;

      const html = buildBrandedHtmlEmail({
        salutationName,
        groupHeadName: head.name,
        financialYearLabel: 'FY 2026-27',
        reportDate,
        attachmentFilename,
      });

      // Claim APPROVED → QUEUED before SMTP to reduce double-send races
      const claimed = await this.prisma.emailCampaign.updateMany({
        where: {
          id: c.id,
          status: EmailCampaignStatus.APPROVED,
        },
        data: {
          status: EmailCampaignStatus.QUEUED,
          queuedAt: new Date(),
        },
      });
      if (claimed.count === 0) {
        continue;
      }

      // 2. Dispatch via Nodemailer (or dev simulation fallback)
      let mailResult: Awaited<ReturnType<MailService['sendMail']>>;
      try {
        mailResult = await this.mailService.sendMail({
          to: email,
          subject,
          html,
          attachments: [
            {
              filename: attachmentFilename,
              content: pdf.buffer,
              contentType: 'application/pdf',
            },
          ],
        });
      } catch (err: any) {
        await this.prisma.emailCampaign.update({
          where: { id: c.id },
          data: {
            status: EmailCampaignStatus.FAILED,
            failedAt: new Date(),
            failureReason: err?.message || 'SMTP send failed',
            retryCount: c.retryCount + 1,
          },
        });
        await this.prisma.deliveryLog.create({
          data: {
            campaignId: c.id,
            groupHeadId: head.id,
            clientName: head.name,
            recipientEmail: email,
            attachmentFilename,
            status: EmailCampaignStatus.FAILED,
            provider: 'Nodemailer (SMTP Relay)',
            failureReason: err?.message || 'SMTP send failed',
            retryCount: c.retryCount + 1,
          },
        });
        continue;
      }

      const now = new Date();
      await this.prisma.emailCampaign.update({
        where: { id: c.id },
        data: {
          status: EmailCampaignStatus.SENT,
          sentAt: now,
          providerMessageId: mailResult.messageId,
          failureReason: null,
          bounceCode: null,
        },
      });

      await this.prisma.deliveryLog.create({
        data: {
          campaignId: c.id,
          groupHeadId: head.id,
          clientName: head.name,
          recipientEmail: email,
          attachmentFilename,
          status: EmailCampaignStatus.SENT,
          provider:
            mailResult.method === 'smtp'
              ? 'Nodemailer (SMTP Relay)'
              : 'Nodemailer (Dev Simulation)',
          providerMessageId: mailResult.messageId,
          retryCount: c.retryCount,
        },
      });

      sentCount += 1;
      dispatchedIds.push(head.id);
    }

    return {
      sentCount,
      dispatchedIds,
      dispatchedBy: user.name,
      overview: await this.listCampaignsAndOverview(reportDate),
    };
  }

  async retryFailedLog(logId: string, alternateEmail?: string) {
    const log = await this.prisma.deliveryLog.findUnique({
      where: { id: logId },
      include: {
        campaign: {
          include: { groupHead: { include: { familyMembers: true } } },
        },
      },
    });

    if (!log) {
      throw new NotFoundException(`Delivery log ${logId} not found.`);
    }

    const reportDate = log.campaign.reportDate;
    await this.freezeService.assertPeriodFrozenForDispatch(reportDate);

    const head = log.campaign.groupHead;
    const recipient = alternateEmail?.trim() || log.recipientEmail;
    if (!recipient || !recipient.includes('@')) {
      throw new BadRequestException('Valid recipient email is required to retry.');
    }

    const pdf = await this.reportsService.generateClientPdf({
      groupHeadId: head.id,
      period: reportDate,
      encrypted: true,
    });
    if (pdf.engine !== 'libreoffice' || pdf.needsReview) {
      throw new ServiceUnavailableException(
        `Retry blocked: PDF engine is ${pdf.engine} (LibreOffice required).`,
      );
    }

    const safeName = head.name.replace(/\s+/g, '_');
    const attachmentFilename =
      log.attachmentFilename ||
      `FY_Annual_Dashboard_${safeName}_${reportDate}.pdf`;
    const subject = `ProAffluence FY Annual Dashboard — ${head.name} — as on ${reportDate}`;
    const salutationName =
      head.familyMembers[0]?.name || head.contactPerson || head.name;
    const html = buildBrandedHtmlEmail({
      salutationName,
      groupHeadName: head.name,
      financialYearLabel: 'FY 2026-27',
      reportDate,
      attachmentFilename,
    });

    let mailResult: Awaited<ReturnType<MailService['sendMail']>>;
    try {
      mailResult = await this.mailService.sendMail({
        to: recipient,
        subject,
        html,
        attachments: [
          {
            filename: attachmentFilename,
            content: pdf.buffer,
            contentType: 'application/pdf',
          },
        ],
      });
    } catch (err: any) {
      const reason = err?.message || 'SMTP retry failed';
      await this.prisma.deliveryLog.update({
        where: { id: log.id },
        data: {
          recipientEmail: recipient,
          status: EmailCampaignStatus.FAILED,
          failureReason: reason,
          retryCount: log.retryCount + 1,
        },
      });
      await this.prisma.emailCampaign.update({
        where: { id: log.campaignId },
        data: {
          status: EmailCampaignStatus.FAILED,
          failedAt: new Date(),
          failureReason: reason,
          retryCount: log.campaign.retryCount + 1,
        },
      });
      throw err;
    }

    const now = new Date();
    await this.prisma.deliveryLog.update({
      where: { id: log.id },
      data: {
        recipientEmail: recipient,
        status: EmailCampaignStatus.SENT,
        timestamp: now,
        failureReason: null,
        bounceCode: null,
        providerMessageId: mailResult.messageId,
        retryCount: log.retryCount + 1,
      },
    });

    await this.prisma.emailCampaign.update({
      where: { id: log.campaignId },
      data: {
        status: EmailCampaignStatus.SENT,
        sentAt: now,
        failureReason: null,
        bounceCode: null,
        providerMessageId: mailResult.messageId,
        retryCount: log.campaign.retryCount + 1,
      },
    });

    return {
      retried: true,
      logId: log.id,
      status: 'Sent',
      overview: await this.listCampaignsAndOverview(reportDate),
    };
  }
}
